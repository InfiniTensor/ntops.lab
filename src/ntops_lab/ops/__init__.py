def get_op(name: str):
    category = _OP_TO_CATEGORY[name]
    module = import_module(_CATEGORY_MODULES[category])
    return getattr(module, name)

def __getattr__(name: str):
    if name in _OP_TO_CATEGORY:
        return get_op(name)
    raise AttributeError(name)

def call(name: str, *args, **kwargs):
    return get_op(name)(*args, **kwargs)

__all__ = sorted([*_OP_TO_CATEGORY, "call", "get_op"])
